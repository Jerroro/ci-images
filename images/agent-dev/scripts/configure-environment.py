"""Build-time only: expose relocated tools to login shells and SSH.

No credentials, runtime installers or sshd_config changes. /etc/environment is
for PAM; profile.d covers login shells; default-PATH wrappers also work when a
host-mounted sshd_config does not use PAM. Preserve activated project venv PATH.
"""

import os
from pathlib import Path
import re
import shlex


ENV_KEYS = (
    "PATH", "LANG", "PYTHONUNBUFFERED", "PIP_NO_CACHE_DIR", "UV_NO_PROGRESS",
    "COREPACK_DEFAULT_TO_LATEST", "COREPACK_ENABLE_DOWNLOAD_PROMPT",
    "COREPACK_ENABLE_AUTO_PIN", "COREPACK_ENABLE_STRICT",
    "GOROOT", "GOPATH", "GOTOOLCHAIN", "RUSTUP_HOME", "CARGO_HOME",
)
TOOLS = {
    **{name: "/opt/agent-tools/bin/" + name for name in (
        "codex", "opencode", "pi", "pnpm", "yarn", "yarnpkg",
        "tsc", "eslint", "prettier", "pyright", "pyright-langserver",
    )},
    **{name: "/opt/node/bin/" + name for name in ("node", "npm", "npx")},
    **{name: "/opt/python-tools/bin/" + name for name in ("uv", "uvx", "poetry", "pipx")},
    **{name: "/opt/go/bin/" + name for name in ("go", "gofmt")},
    "golangci-lint": "/opt/go-tools/bin/golangci-lint",
    "agy": "/opt/antigravity/bin/agy",
    "corepack": "/opt/corepack-tools/bin/corepack",
    **{name: "/opt/rust/bin/" + name for name in (
        "rustc", "cargo", "rustup", "rustfmt", "cargo-fmt", "cargo-clippy",
        "clippy-driver", "rustdoc",
    )},
}
MARKER = "# Generated by agent-container configure-environment.py"


def configure(root=Path("/"), environment=None):
    environment = os.environ if environment is None else environment
    values = {key: environment[key] for key in ENV_KEYS}
    for key, value in values.items():
        if not re.fullmatch(r"[A-Za-z0-9_:/.-]+", value):
            raise ValueError(f"Unsafe/non-literal image environment: {key}")
    # Validate everything before writing. Wrapper and target must differ.
    for name, target in TOOLS.items():
        if not (root / target.lstrip("/")).is_file():
            raise FileNotFoundError(f"Missing image tool: {target}")
        destination = root / "usr/local/bin" / name
        if destination.exists() or destination.is_symlink():
            if destination.is_symlink() or MARKER not in destination.read_text():
                raise FileExistsError(f"Refusing to replace an unrelated tool: {destination}")

    profile = root / "etc/profile.d/agent-env.sh"
    profile.parent.mkdir(parents=True, exist_ok=True)
    lines = [MARKER]
    for key, value in values.items():
        if key in {"PATH", "GOROOT", "RUSTUP_HOME"}:
            lines.append(f"export {key}={shlex.quote(value)}")
        elif key == "CARGO_HOME":
            lines.append('export CARGO_HOME="${CARGO_HOME:-$HOME/.cargo}"')
        elif key == "GOPATH":
            lines.append('export GOPATH="${GOPATH:-$HOME/go}"')
        else:
            lines.append(f'export {key}="${{{key}:-{value}}}"')
    profile.write_text("\n".join(lines) + "\n")
    profile.chmod(0o644)
    pam = root / "etc/environment"
    pam.write_text(MARKER + "\n" + "".join(
        f'{key}="{value}"\n' for key, value in values.items()
    ))
    pam.chmod(0o644)

    bindir = root / "usr/local/bin"
    bindir.mkdir(parents=True, exist_ok=True)
    for name, target in TOOLS.items():
        wrapper = bindir / name
        wrapper.write_text(
            "#!/bin/sh\n" + MARKER + "\n"
            "agent_original_path=${PATH-}\n"
            ". /etc/profile.d/agent-env.sh\n"
            'if [ -n "$agent_original_path" ]; then\n'
            '    PATH=$agent_original_path; export PATH\n'
            "fi\n"
            f'exec {shlex.quote(target)} "$@"\n'
        )
        wrapper.chmod(0o755)


if __name__ == "__main__":
    configure()
